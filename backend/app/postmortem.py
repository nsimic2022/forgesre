"""One-click postmortem: a Markdown draft built from what ForgeSRE already knows.

Facts only: times, timeline, notifications, notes, what changed before, the review's root
cause, ForgeRCA's facts and suggested actions, playbook progress. Nothing is invented; gaps
are left as [to fill] so the team writes them in the review meeting. Blameless by wording.
"""

from __future__ import annotations

from datetime import datetime
from typing import Any
from zoneinfo import ZoneInfo

from sqlalchemy.orm import Session

from app.models import Incident, User
from app.settings import settings

TODO = "[to fill]"


def _when(iso: str | None) -> str:
    if not iso:
        return "—"
    value = datetime.fromisoformat(iso)
    return value.astimezone(ZoneInfo(settings.timezone or "UTC")).strftime("%Y-%m-%d %H:%M")


def _minutes(a: str | None, b: str | None) -> int | None:
    if not a or not b:
        return None
    return max(0, int((datetime.fromisoformat(b) - datetime.fromisoformat(a)).total_seconds() // 60))


def _dur(minutes: int | None) -> str:
    if minutes is None:
        return "—"
    return f"{minutes} min" if minutes < 60 else f"{minutes // 60} h {minutes % 60} min"


def _behind(db: Session, incident: Incident) -> int:
    """Assets behind this one in the dependency map (they were kept quiet while it was down)."""
    from app.models import Asset

    if incident.asset_id is None:
        return 0
    count, frontier = 0, [incident.asset_id]
    for _ in range(12):
        rows = db.query(Asset.id).filter(Asset.parent_id.in_(frontier)).all()
        frontier = [r[0] for r in rows]
        if not frontier:
            break
        count += len(frontier)
    return count


def postmortem_markdown(db: Session, incident: Incident, user: User) -> str:
    """Draft for the review meeting. Uses the same view as the incident page (evidence follows the user's role)."""
    from app.incident_view import incident_view

    v = incident_view(db, incident, user)
    asset = v.get("asset") or {}
    tta, ttr = _minutes(v["started_at"], v["ack_at"]), _minutes(v["started_at"], v["resolved_at"])
    review = v["review"]
    rca = v.get("forgerca") or {}
    cause = review["root_cause"] or ""
    out: list[str] = [
        f"# Incident review: {v['number']} · {v['title']}",
        "",
        f"*Draft generated by ForgeSRE on {datetime.now(ZoneInfo(settings.timezone or 'UTC')).strftime('%Y-%m-%d %H:%M')}. "
        "Blameless: describe what the system and the process did, not who is at fault.*",
        "",
        "## Summary",
        "",
        "| | |",
        "|---|---|",
        f"| Severity | {v['severity']} |",
        f"| Asset | {asset.get('hostname') or '—'}{(' · ' + asset['type']) if asset.get('type') else ''} |",
        f"| Started | {_when(v['started_at'])} |",
        f"| Acknowledged | {_when(v['ack_at'])}{(' by ' + v['ack_by']) if v['ack_by'] else ''} · after {_dur(tta)} |",
        f"| Resolved | {_when(v['resolved_at'])}{(' by ' + v['resolved_by']) if v['resolved_by'] else ''} · after {_dur(ttr)} |",
        f"| Highest escalation level | {v['level'] or '—'} |",
        f"| Rule / playbook | {v['playrule'] or '—'} / {(v['playbook'] or {}).get('name') or '—'} |",
        "",
    ]
    written = ((v.get("forgeai") or {}).get("extras") or {}).get("postmortem")
    if written and (written.get("answer") or {}).get("paragraph"):
        out += ["## In short", "", f"{written['answer']['paragraph']}", "",
                "*Written by ForgeAI from the facts, notes and timeline above; check it before the meeting.*", ""]
    out += ["## Impact", ""]
    behind = _behind(db, incident)
    if behind:
        out.append(f"- {behind} asset(s) sit behind {asset.get('hostname')} in the dependency map; their alarms were held back while it was down.")
    out += [f"- Users and services affected: {TODO}", f"- Customer-visible: {TODO}", "", "## Root cause", ""]
    if cause:
        out.append(f"{cause} *(from the incident review by {review['reviewed_by'] or 'the team'})*")
    elif rca.get("cause"):
        out.append(f"{TODO} ForgeRCA suggested: *{rca['cause']}* (not yet confirmed in a review).")
    else:
        out.append(TODO)
    out += ["", "## What changed before", ""]
    changes = v.get("changes") or []
    if changes:
        for c in changes[:10]:
            link = f" ([link]({c['url']}))" if c.get("url") else ""
            out.append(f"- {_dur(c['before_min'])} before · **{c['kind']}** · {c['title']}{link}" + (f" · {c['asset']}" if c.get("asset") else ""))
    else:
        out.append("No change recorded in the 24 hours before.")
    out += ["", "## Timeline", "", "| Time | What happened |", "|---|---|"]
    events: list[tuple[str, str]] = [(v["started_at"] or "", f"Alarm opened the incident ({v['source'] or 'alert'})")]
    for item in v.get("timeline") or []:
        if item.get("at"):
            text = " · ".join(str(x) for x in (item.get("title"), item.get("detail")) if x)
            events.append((str(item["at"]), text))
    for n in v.get("notifications") or []:
        if n.get("at") or n.get("created_at"):
            events.append((str(n.get("at") or n.get("created_at")), f"{n.get('channel', 'email')} to {n.get('target')}: {n.get('status')}"))
    for note in v.get("notes") or []:
        if note.get("at"):
            events.append((note["at"], f"Note by {note['actor']}: {str(note['body'])[:160]}"))
    if v["ack_at"]:
        events.append((v["ack_at"], f"Acknowledged by {v['ack_by'] or '—'}"))
    if v["resolved_at"]:
        events.append((v["resolved_at"], f"Resolved by {v['resolved_by'] or '—'}"))
    for at, text in sorted(events, key=lambda e: e[0]):
        out.append(f"| {_when(at)} | {text.replace('|', '/')} |")
    if rca.get("facts"):
        out += ["", "## What ForgeRCA found", ""]
        for fact in rca["facts"][:12]:
            out.append(f"- {fact.get('text') if isinstance(fact, dict) else fact}")
    playbook = v.get("playbook")
    if playbook:
        out += ["", f"## Playbook · {playbook['name']}", ""]
        for i, step in enumerate(playbook["steps"]):
            out.append(f"- [{'x' if i in playbook['done'] else ' '}] {step}")
    out += ["", "## What went well", "", f"- {TODO}", "", "## What to improve", "", f"- {TODO}", "", "## Follow-up actions", "",
            "| Action | Owner | Due |", "|---|---|---|"]
    for item in v.get("actions") or []:
        done = " *(done)*" if item["done"] else ""
        out.append(f"| {item['text'].replace('|', '/')}{done} | {item['owner'] or TODO} | {item['due'] or TODO} |")
    for action in (rca.get("actions") or [])[:6]:
        out.append(f"| {str(action).replace('|', '/')} *(ForgeRCA suggestion)* | {TODO} | {TODO} |")
    out.append(f"| {TODO} | {TODO} | {TODO} |")
    if review["rca_rating"] or review["ai_rating"]:
        out += ["", "## How good were the suggestions", "",
                f"- ForgeRCA: {review['rca_rating'] or 'not rated'} · ForgeAI: {review['ai_rating'] or 'not rated'}"]
    return "\n".join(out) + "\n"
